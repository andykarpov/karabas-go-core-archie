#!/usr/bin/env python3
"""Makes rtl/karabas_mini_top.v and rtl/karabas_go_top.v from rtl/karabas_minig_top.v (link v2).

The three tops share the core logic; the board glue differs. Change the Mini G top, then run this
(every replacement must match exactly once, else it stops). The header comment and the port list
of Mini / Go come from git (the last v1 tops, ref V1_REF), the body from Mini G.

Mini (before rev.G): MCU_SCK not on a clock pin, MCU_IO of 4 bits (INT on MCU_IO[1]), sigma-delta
  audio on AUDIO_L / AUDIO_R, the MIDI clock of the SAM2695, FT_RESET / ESP pins inactive.
Go: INT on MCU_SPI_IO[0] (the burst ready line of v1), the FT / SD2 selects on MCU_SPI_*_CS_N, VGA
  with V_CLK (no HDMI, no DCM, no FT_CLK_OUT), DAC_LRCK / DAC_MUTE, FLASH_CS_N = 1, the floppy
  connector unused (its outputs 0).
"""
import os
import subprocess
import sys

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RTL = os.path.join(SRC, "rtl")
V1_REF = "5cacc88"  # master before link v2


def sub(s, old, new, what):
    if s.count(old) != 1:
        sys.exit("mktops.py: %s: %d matches of %r" % (what, s.count(old), old[:70]))
    return s.replace(old, new)


def v1(board):
    return subprocess.check_output(["git", "show", "%s:src/rtl/karabas_%s_top.v" % (V1_REF, board)],
                                   cwd=SRC).decode()


def head(s):
    i = s.index("module karabas_")
    return s[:s.index("\n);\n", i) + 4]


def body(s):
    i = s.index("module karabas_")
    return s[s.index("\n);\n", i) + 4:]


MCU_SCK_G = """wire mcu_sck_ibufg, mcu_sck;
IBUFG ibufg_mcu_sck (.I(MCU_SCK), .O(mcu_sck_ibufg));
BUFG bufg_mcu_sck (.I(mcu_sck_ibufg), .O(mcu_sck));"""
MCU_SCK_OLD = """// MCU_SCK is not on a clock pin before rev.G (CLOCK_DEDICATED_ROUTE = FALSE in the ucf)
wire mcu_sck = MCU_SCK, mcu_sck_ibufg = MCU_SCK;"""
PLL_G = "	.BUFG_MASK(6'b001111)"
PLL_MIDI = "	.CLKOUT4_DIVIDE(67),     // 11.94 MHz: MIDI_CLK of the SAM2695\n	.BUFG_MASK(6'b011111)"
MIDI_ODDR = "\nODDR2 oddr_midi_clk (.Q(MIDI_CLK), .C0(pll_clk[4]), .C1(~pll_clk[4]), .CE(1'b1), .D0(1'b1), .D1(1'b0), .R(1'b0), .S(1'b0));\n"
PCM = """kg_pcm5102 #(.DIV_BITS(2)) dac (  // bck 5 MHz, 156 kHz
	.clk(clk_sys),
	.reset(areset),
	.left(audio_l),
	.right(audio_r),
	.din(DAC_DAT),
	.bck(DAC_BCK),
	.lrck(DAC_WS)
);"""

minig = open(os.path.join(RTL, "karabas_minig_top.v")).read()
b = body(minig)
pll_end = "ODDR2 oddr_ft_clk (.Q(FT_CLK_OUT), .C0(clk_8), .C1(~clk_8), .CE(1'b1), .D0(1'b1), .D1(1'b0), .R(1'b0), .S(1'b0));\n"

# ---------------------------------------------------------------- Mini
m = b
m = sub(m, "assign ESP32_SPI_CS_N = 1'b1;\n", "assign ESP_RESET_N = 1'bz;\nassign ESP_BOOT_N = 1'bz;\n"
        "assign MIDI_RESET_N = 1'b1;\nassign FT_RESET = 1'b1;\n", "mini esp")
m = sub(m, PLL_G, PLL_MIDI, "mini pll")
m = sub(m, pll_end, pll_end + MIDI_ODDR, "mini midi clk")
m = sub(m, MCU_SCK_G, MCU_SCK_OLD, "mini mcu_sck")
m = sub(m, "assign MCU_IO[5:2] = 4'bzzzz;", "assign MCU_IO[3:2] = 2'bzz;", "mini mcu_io")
m = sub(m, PCM, """// no I2S DAC on this board: sigma-delta outputs into an RC filter, offset binary input
kg_sigma_delta_dac dac_l (.clk(clk_sys), .reset(areset), .din({ ~audio_l[15], audio_l[14:0] }), .dout(AUDIO_L));
kg_sigma_delta_dac dac_r (.clk(clk_sys), .reset(areset), .din({ ~audio_r[15], audio_r[14:0] }), .dout(AUDIO_R));""",
        "mini dac")
mini = head(v1("mini")).replace("[0] burst cs_n, [1] burst ready, [2] sd2 cs_n, [3] ft cs_n",
                                "[1] INT of link v2, [2] sd2 cs_n, [3] ft cs_n")
mini += "// karabas: generated by src/tools/mktops.py from karabas_minig_top.v (do not edit it, change Mini G)\n" + m

# ---------------------------------------------------------------- Go
g = b
g = sub(g, "assign ESP32_SPI_CS_N = 1'b1;\n", """assign ESP_RESET_N = 1'bz;
assign ESP_BOOT_N = 1'bz;
assign MIDI_RESET_N = 1'b1;
assign FT_OE_N = 1'b1;     // the FT812 does not drive the video DAC
assign BEEPER = 1'b0;

// the floppy connector is not used: its outputs 0 (the board inverts them: high = active)
assign FDC_DRIVE = 2'b00;
assign FDC_MOTOR = 1'b0;
assign FDC_DIR = 1'b0;
assign FDC_STEP = 1'b0;
assign FDC_WDATA = 1'b0;
assign FDC_WGATE = 1'b0;
assign FDC_SIDE_N = 1'b0;
""", "go esp")
g = sub(g, "assign ADC_CLK = 1'b0;\nassign ADC_BCK = 1'bz;\nassign ADC_LRCK = 1'bz;\n", "", "go adc")
g = sub(g, "// FLASH_CS_N (T3) is the SDRAM /CS of Mini G2 (rev G: tied low on the board): always selected\nassign FLASH_CS_N = 1'b0;",
        "assign FLASH_CS_N = 1'b1;   // the flash chip; the SDRAM /CS is hard wired on Go", "go flash")
g = sub(g, "wire locked, lockedx5, areset;\nwire clk_hdmi, clk_hdmi_n;", "wire locked, areset;", "go clk decl")
g = sub(g, PLL_G, PLL_MIDI, "go pll")
i = g.index("kg_dcm #(\n\t.CLKIN_PERIOD(25.0),")
j = g.index(pll_end) + len(pll_end)
g = g[:i] + "// the pixel clock of the VGA DAC\nODDR2 oddr_v_clk (.Q(V_CLK), .C0(clk_sys), .C1(~clk_sys), .CE(1'b1), .D0(1'b1), .D1(1'b0), .R(1'b0), .S(1'b0));" + MIDI_ODDR + g[j:]
g = sub(g, MCU_SCK_G, MCU_SCK_OLD, "go mcu_sck")
g = sub(g, """assign MCU_IO[1] = mcu_int;
assign MCU_IO[0] = 1'bz;
assign MCU_IO[5:2] = 4'bzzzz;""", """// Go: INT on MCU_SPI_IO[0] (the burst ready line of v1)
assign MCU_SPI_IO[0] = mcu_int;
assign MCU_SPI_IO[1] = 1'bz;""", "go mcu_io")
g = sub(g, ".MCU_SPI_FT_SS(MCU_IO[3]),", ".MCU_SPI_FT_SS(MCU_SPI_FT_CS_N),", "go ft ss")
g = sub(g, ".MCU_SPI_SD2_SS(MCU_IO[2]),", ".MCU_SPI_SD2_SS(MCU_SPI_SD2_CS_N),", "go sd2 ss")
g = sub(g, "	.lrck(DAC_WS)\n);", "	.lrck(DAC_LRCK)\n);\nassign DAC_MUTE = 1'b1;  // soft mute of the PCM5102: 1 = sound on", "go dac")
i = g.index("// 48 kHz for hdmi_tx")
j = g.index(");", g.index("hdmi_tx #(")) + 2
g = g[:i] + """// ------------------------------------------------------------------ VGA

assign VGA_R = osd_rgb[23:16];
assign VGA_G = osd_rgb[15:8];
assign VGA_B = osd_rgb[7:0];
assign VGA_HS = osd_hs;
assign VGA_VS = osd_vs;""" + g[j:]
go = head(v1("go")).replace("[0] burst ready (firmware IO1, GPIO2), [1] burst cs_n (IO0, GPIO14)",
                            "[0] INT of link v2 (firmware IO1, GPIO2)")
go += "// karabas: generated by src/tools/mktops.py from karabas_minig_top.v (do not edit it, change Mini G)\n" + g

open(os.path.join(RTL, "karabas_mini_top.v"), "w").write(mini)
open(os.path.join(RTL, "karabas_go_top.v"), "w").write(go)
print("mktops.py: karabas_mini_top.v, karabas_go_top.v")
